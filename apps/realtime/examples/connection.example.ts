/**
 * CLIENT connection wiring (reference) — activate AFTER `spacetime generate` (see the setup doc).
 *
 * NOT part of @chassix/realtime's tsconfig build: it imports `./module_bindings`, which only
 * exists once you run `spacetime generate --lang typescript --out-dir apps/realtime/src/module_bindings`.
 * Once generated, move this into `src/`, fix the import path, and it type-checks against the real
 * `DbConnection`. The rest of @chassix/realtime (`transport`, `publisher`, `subscribe`) already
 * works against the generated connection because it structurally satisfies `RunEventConnection`.
 */
// @ts-nocheck
import { DbConnection } from "./module_bindings"; // generated by `spacetime generate`
import { connectionPublisher, SpaceTimeDBEventTransport } from "../src/index.js";

export interface SpacetimeConfig {
  uri: string; // SPACETIME_URI, e.g. wss://maincloud.spacetimedb.com or ws://localhost:3000
  moduleName: string; // SPACETIME_MODULE, the published module name/identity
  token?: string; // SPACETIME_TOKEN (OIDC JWT); omit to get an anonymous identity
}

/** Build a live connection to the published module. */
export function connectSpacetime(cfg: SpacetimeConfig): Promise<DbConnection> {
  return new Promise((resolve, reject) => {
    const builder = DbConnection.builder()
      .withUri(cfg.uri)
      .withModuleName(cfg.moduleName)
      .onConnect((conn) => resolve(conn))
      .onConnectError((_ctx, err) => reject(err));
    if (cfg.token) builder.withToken(cfg.token);
    builder.build();
  });
}

/** Server-side (orchestrator) usage: publish events to the live layer. */
export async function makeTransport(cfg: SpacetimeConfig) {
  const conn = await connectSpacetime(cfg);
  return new SpaceTimeDBEventTransport(connectionPublisher(conn));
}
